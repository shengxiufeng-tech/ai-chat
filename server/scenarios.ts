export function improvScenario(theme: string, era: Era, eraLabel?: string): ScenarioInfo {
  const t = theme.trim() || '一座偏僻小镇里的失踪事件';
  const label = eraLabel?.trim() || (era === 'modern' ? '现代' : '1920 年代');
  return {
    id: 'improv',
    title: `即兴剧本：${t.length > 16 ? `${t.slice(0, 16)}…` : t}`,
    era,
    eraLabel: label,
    intro: `守秘人会根据主题「${t}」即兴创作一个短篇调查故事。`,
    secret: `【没有预设剧本，请你即兴创作】
主题：${t}
时代背景：${label}

请先在心里构思好（不要写出来给玩家看）：
1. 事件的真相：发生了什么、背后的神话存在或邪教是什么。
2. 3~5 个可以调查的地点，每个地点有 1~2 条关键线索，线索之间互相指向。
3. 2~4 个有动机、有秘密的 NPC。
4. 至少两种结局（好结局和坏结局），以及达成的条件。
5. 2~3 次理智检定的时机和损失（一般为 0/1 到 1/1d6）。
这是一个适合新手、1~2 小时可以完成的短篇。开场时交代调查员为什么会卷入事件，然后逐步展开。保持前后设定一致。

重要：你构思的这些内容不会被自动保存。请在第一次回复的末尾，用秘密备忘指令把真相、关键 NPC 的秘密和结局条件记下来（玩家看不到），例如 [备忘:真相:……]、[备忘:结局:……]；之后剧情有新的决定时也随时更新。`,
  };
}

export function customScenario(text: string, era: Era): ScenarioInfo {
  const firstLine = text.trim().split('\n')[0]?.replace(/^[#\s【]+|[】\s]+$/g, '') || '自定义剧本';
  return {
    id: 'custom',
    title: firstLine.slice(0, 24),
    era,
    eraLabel: era === 'modern' ? '现代' : '1920 年代',
    intro: '使用你提供的剧本。',
    secret: `【剧本（由玩家提供，按照这个剧本主持）】\n${text.trim()}`,
  };
}
